const dicts: Record<Lang, Record<Key, string>> = { de, en };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  const d = dicts[lang] ?? de;
  return (key, vars) => {
    let s = d[key] ?? de[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

/** Picks the text for the current language, falling back to English, then anything. */
export function loc<V>(m: Localized<V> | undefined | null, lang: Lang): V | undefined {
  if (!m) return undefined;
  return m[lang] ?? m.en ?? Object.values(m)[0];
}

export function errorText(t: T, e: { code: string; message: string }): string {
  const key = `err.${e.code}` as Key;
  return key in de ? t(key) : e.message;
}
